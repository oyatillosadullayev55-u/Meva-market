class Product {
  final String id;
  final String nameKey;
  final double price;
  final String unit;
  final String imageUrl;
  final String categoryKey;
  final String descKey;
  final double rating;

  Product({
    required this.id,
    required this.nameKey,
    required this.price,
    required this.unit,
    required this.imageUrl,
    required this.categoryKey,
    required this.descKey,
    required this.rating,
  });
}
